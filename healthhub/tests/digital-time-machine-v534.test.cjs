'use strict';
/* On-demand, deterministic time-machine QA. Real production Web vault
 * validators, synthetic fixture events, and native consent-gate contract. */
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const machine=require('../digital-health/time-machine-v534.js');
const vault=require('../digital-health/digital-usage-vault-v507.js');
const html=fs.readFileSync(path.join(root,'digital-health/time-machine-v534.html'),'utf8');
const code=fs.readFileSync(path.join(root,'digital-health/time-machine-v534.js'),'utf8');
const native=fs.readFileSync(path.join(root,'android-bridge/app/src/main/java/hu/zsoltmonika/healthhubbridge/dw/DigitalUsageCloudSync.kt'),'utf8');
const HOUR=3_600_000;
function run(minutes,mode='normal'){return machine.simulate({minutes,mode},vault)}
const before=run(-32);
assert.equal(before.localRows,6,'Mónika-style six preconsent local rows');
assert.equal(before.firstAllowed,machine.FIRST,'Next fully consented UTC bucket');
assert.equal(before.eligibleRows,0,'At 23:28 no app identity may pass midnight consent gate');
assert.equal(before.publishedRows,0);
assert.equal(before.validation,'PASS','Real vault accepts safe empty app list');
assert.equal(before.coarseRows,1,'Previous coarse data still shares');
const twenty=run(20);
assert.equal(twenty.localRows,6,'Current 00:00–01:00 partial hour cannot be fabricated');
assert.equal(twenty.eligibleRows,0);
assert.equal(twenty.publishedRows,0);
const ready=run(65);
assert.equal(ready.localRows,8,'New completed hour yields two additional app rows');
assert.equal(ready.eligibleRows,2,'Consent gate passes 00:00 completed hour');
assert.equal(ready.publishedRows,2,'Matching coarse-hour enables cloud app rows');
assert.equal(ready.coarseRows,2);
assert.equal(ready.topApps.length,2,'Actual production web validator and summary populate app list');
assert.equal(ready.validation,'PASS');
const missing=run(65,'missing-coarse');
assert.equal(missing.localRows,8);
assert.equal(missing.eligibleRows,2,'Missing coarse cannot mislabel as missing consent');
assert.equal(missing.publishedRows,0,'Without matching coarse-hour, no leaked app details');
assert.equal(missing.validation,'PASS');
const unshared=run(65,'unshared');
assert.equal(unshared.localRows,8);
assert.equal(unshared.eligibleRows,0,'No per-app consent means no app sharing');
assert.equal(unshared.publishedRows,0);
assert.equal(unshared.validation,'PASS');
const invalid=run(65,'invalid-hour');
assert.equal(invalid.passed,false,'Impossible foreground usage is rejected');
assert.equal(invalid.publishedRows,0,'Never submit invalid synthetic data');
assert.match(invalid.error,/egyórás/);
assert.throws(()=>run(181),/outside/);
assert.throws(()=>run(65,'unknown'),/Unknown/);
const edgeAtOne=run(60);
assert.equal(edgeAtOne.eligibleRows,2,'At 01:00 precisely the first hour is complete');
assert.equal(machine.ceilUtcHour(machine.CLOUD_CONSENT),machine.FIRST,'Real consent rounds up to midnight boundary');
assert.ok(!code.includes('fetch('),'Test model never performs external requests');
assert.ok(!/(localStorage|sessionStorage|indexedDB|XMLHttpRequest|navigator\.serviceWorker)/.test(code),'No user data, permissions, caches, or tokens');
assert.ok(html.includes("connect-src 'none'"),'CSP absolutely prevents any cloud/network requests');
assert.ok(html.includes('SZINTETIKUS TESZT · NEM VALÓDI MÉRÉS'),'No confusion with actual phone data');
assert.ok(html.includes('digital-usage-vault-v507.js'),'Use true HealthHub web validation, not mock');
assert.ok(html.includes('time-machine-v534.js'),'Only synthetic controller is user-triggered');
assert.ok(!/(hh-dropbox-token|authorization:|api.dropbox|real patient|personal data)/i.test(code),'No private credentials');
assert.ok(native.includes('maxOf(localConsent, cloudConsent)'),'Native gate honors BOTH consents');
assert.ok(native.includes('UsageSessionizer.HOUR_MS - 1L'),'Native gate rounds to first whole hour');
assert.ok(native.includes('it.hourStartMs >= since && it.hourStartMs in observedHourKeys'),'Native gate requires permitted and paired coarse hour');
assert.ok(native.includes('p.getBoolean(PilotState.CLOUD_DETAIL_ENABLED, false)'),'Independent app cloud opt-in is protected');
assert.ok(native.includes('val appArr = JSONArray()'),'Native output still uses consent-filtered app rows');
console.log('PASS Digital Wellbeing Time Machine v534: six synthetic app rows, clock jump 23:28→00:20→01:05, two consents, matching coarse hour, no consent, invalid usage, real web validator, native source contract and zero-network CSP.');
