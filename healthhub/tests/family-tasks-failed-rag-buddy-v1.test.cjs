'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path'),vm=require('node:vm');
const root=path.resolve(__dirname,'../..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('sh9/family-hub/index.html');
const ui=read('sh9/family-hub/family-tasks-v880.js');
const notifier=read('sh9/family-hub/family-notifier-v880.js');
const css=read('sh9/family-hub/family-failed-buddy-v1.css');
const sleepCss=read('healthhub/sleep-rag-buddy-v1146.css');
const migration=read('supabase/migrations/20261104194500_family_tasks_closed_failed_rag_buddy.sql');
test('four task states, separate closed counter, not overdue, still searchable and logged',()=>{
 assert.match(ui,/failed:'⚫ Nem teljesült'/);
 assert.match(ui,/\['failed','⚫ Nem teljesült'\]/);
 assert.match(ui,/function isClosed\(t\)/);
 assert.match(ui,/t\.due_at&&!isClosed\(t\)/);
 assert.match(ui,/\['fhFailedCount','failed'\]/);
 assert.match(html,/id="fhFailedCount"/);
 assert.match(ui,/is-failed/);
 assert.match(ui,/isClosed\(task\)/);
 assert.match(ui,/fh-failed-label/);
 assert.match(ui,/t\.status==='failed'\?t\.closed_at:t\.completed_at/);
 assert.match(ui,/status,due_at,completed_at,closed_at,reaction,stars,revision/);
 assert.match(ui,/from\(LOG\)/);
});
test('all three original approved RAG Buddy sprite poses are reused exactly',()=>{
 const capture=css.match(/background-image:url\("data:image\/webp;base64,([A-Za-z0-9+/=]+)"\)/);
 const baseline=sleepCss.match(/background-image:url\("data:image\/webp;base64,([A-Za-z0-9+/=]+)"\)/);
 assert.ok(capture&&baseline);
 assert.equal(capture[1],baseline[1],'all outcomes share the existing approved Buddy sprite, not a newly generated image');
 const blob=Buffer.from(capture[1],'base64');
 assert.equal(blob.toString('ascii',0,4),'RIFF');
 assert.equal(blob.toString('ascii',8,12),'WEBP');
 assert.match(css,/background-size:100% 300%/);
 assert.match(css,/data-rag="green"\][\s\S]*background-position:center 0%/);
 assert.match(css,/data-rag="amber"\][\s\S]*background-position:center 50%/);
 assert.match(css,/data-rag="red"\][\s\S]*background-position:center 100%/);
 assert.match(ui,/pose\.dataset\.rag=t\.status==='done'\?'green':t\.status==='progress'\?'amber':'red'/);
 assert.match(html,/id="fhOutcomeBuddy"/);
 assert.match(notifier,/pose\.dataset\.rag=state==='done'\?'green':state==='progress'\?'amber':'red'/);
});
test('feedback: green success TADAAA, amber progress, red sad closed, no success music for failure',()=>{
 assert.match(ui,/function showTaskOutcome\(result,title\)/);
 assert.match(ui,/failed:'Nem teljesült'/);
 assert.match(ui,/progress:'Folyamatban'/);
 assert.match(ui,/if\(result==='done'\)playTada\(\)/);
 assert.match(ui,/overlay\.dataset\.result=result/);
 assert.match(notifier,/A feladat nem teljesült, lezárva/);
 assert.match(notifier,/A feladat folyamatban van/);
 assert.match(notifier,/const state=e\.event_type==='status'\?e\.current_value\?\.status:null/);
 assert.match(notifier,/fh-notice-rag-buddy/);
});
test('dedicated failure closure timestamp never spoofs successful completion; actor/profile verification preserved',()=>{
 assert.match(migration,/check \(status in \('todo','progress','done','failed'\)\)/);
 assert.match(migration,/add column if not exists closed_at timestamptz/);
 assert.match(migration,/new\.closed_at:=case when new\.status='failed'/);
 assert.match(migration,/new\.completed_at:=case when new\.status='done'/);
 assert.match(migration,/if new\.status='failed' and old\.status<>'failed'/);
 assert.match(migration,/elsif new\.status<>'done' then new\.completed_at:=null/);
 assert.match(migration,/new\.revision:=old\.revision\+1/);
 assert.match(migration,/auth\.uid\(\)/);
 assert.match(migration,/hh_profile_access/);
 assert.doesNotMatch(migration,/disable row level security|drop policy/i);
});
