assert.match(worker,/OneOpsLog\.record\(prefs, "orchestrator", state\)/);
for(const key of ['healthConnectAvailable','healthReadPermissionCount','lastHealthSyncAt',
 'lastHealthAttemptAt','lastOtaCheckAt','hasDropboxRefreshToken'])
 assert.ok(diag.includes(key),'missing technical metric '+key);
for(const forbidden of ['healthRecords','medicalDocuments','rawAppUsage','userMessageContent','accessToken'])
 assert.ok(!diag.includes('put("'+forbidden+'"'),'personal diagnostic payload leakage: '+forbidden);
assert.match(activity,/Műszaki diagnosztika KI/);
assert.match(activity,/putBoolean\(OneTechnicalDiagnostics.KEY_CONSENT, false\)/);
assert.match(activity,/setPositiveButton\("Engedélyezem"/);
assert.match(activity,/otaCheckFeedback = TextView\(this\)/,'visible OTA status next to button');
assert.match(activity,/otaCheckFeedback\.text = "⏳ Frissítési kiszolgáló/,'immediate progress');
assert.match(activity,/otaCheckButton\.isEnabled = false/,'guard repeated taps');
assert.match(activity,/otaCheckButton\.isEnabled = true/,'restore after completion');
assert.match(activity,/⚠️ OTA ellenőrzés sikertelen/,'network errors not reported as no-update');
assert.match(worker,/if \(owner != null && OneTechnicalDiagnostics\.consent\(prefs\)\) it\.put\("diagnostics"\)/);
assert.match(worker,/owner == null \|\| requestedOwner != owner/);
assert.match(worker,/issued\.isBefore\(now\.minusSeconds/);
assert.match(worker,/deadline\.isAfter\(issued\.plusSeconds/);
assert.match(worker,/commandId == prefs\.getString\(LAST_COMMAND_KEY, null\)/);
assert.match(worker,/requestedScopes = actionScopes/);
assert.match(worker,/technicalSnapshot = OneTechnicalDiagnostics\.snapshot/);
assert.match(worker,/put\("diagnostics", technicalSnapshot\)/);
assert.match(worker,/finalState = if \(failed == 0 && skipped == 0\) "done" else "partial"/);
assert.match(worker,/skipped\+\+ \/\/ Enqueued is not proof/);
