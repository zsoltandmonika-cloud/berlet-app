'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'../..'),read=p=>fs.readFileSync(path.join(root,p),'utf8');
const ai=require('../../sh9/smart-travel/public-transport/smart-trip/smart-trip-chatgpt-handoff-v1076.js');
const html=read('sh9/smart-travel/public-transport/smart-trip/index.html');
const ui=read('sh9/smart-travel/public-transport/smart-trip/smart-trip-ai-v1022.js');
const q={from:'Otthon',to:'Mónika · Anyuka',date:'2026-11-01',time:'07:30',mode:'depart'};
const places={origin:{name:'Otthon',lat:47.54512,lng:19.03534},destination:{name:'Mónika · Anyuka',lat:48.25343,lng:20.64156}};
test('ChatGPT is default, Google is only an explicitly chosen dropdown item, no CTA',()=>{
 assert.match(html,/<option value="chatgpt">✨ Léna · ChatGPT/);
 assert.match(html,/<option value="google">🗺️ Google Térkép/);
 assert.match(html,/<option value="native">🧠 SH9 saját · kísérleti/);
 assert.doesNotMatch(html,/id="st22ExternalTrip"|id="st22ExternalNote"/);
 assert.match(html,/smart-trip-chatgpt-handoff-v1076\.js/);
 assert.match(ui,/if\(method==='chatgpt'\)\{chatgptHandoff\(query\);return\}/);
 assert.match(ui,/if\(method==='google'\)\{googleHandoff\(query\);return\}/);
 assert.match(ui,/if\(method==='chatgpt'\)[\s\S]{0,100}if\(method==='google'\)/);
 assert.match(ui,/form\.addEventListener\('submit',searchTrip\)/);
});
test('ChatGPT handoff includes user selected matched favorites, date, preferences, holidays and verification',()=>{
 const prompt=ai.prompt(q,places,'wait');
 assert.ok(prompt&&prompt.length>450&&prompt.length<1350,'keep route-first prompt concise despite automatic TripPack export');
 assert.match(prompt,/Otthon \(kijelölt hely koordinátája: 47\.54512, 19\.03534\)/);
 assert.match(prompt,/Mónika · Anyuka \(kijelölt hely koordinátája: 48\.25343, 20\.64156\)/);
 assert.match(prompt,/2026-11-01 07:30/);
 assert.match(prompt,/lehető legkevesebb várakozás/i);
 assert.match(prompt,/ünnepi vagy forgalmi eltéréseket/);
 assert.match(prompt,/forráslinket/);
 assert.match(prompt,/bizonytalan időpontokat jelöld becsültnek/);
 assert.match(prompt,/tömegközlekedési utat/);
 assert.doesNotMatch(prompt,/KÜLÖNLEGES NAPOK:|ELLENŐRZÉS:|Személyes egészségügyi adatokat|temetői és forgalmi|időrendi táblázat/);
 assert.match(prompt,/Alternatív útvonalakat ne keress/);
 assert.match(prompt,/Az útiterv UTÁN automatikusan készíts letölthető SH9_TripPack\.json-t/);
 assert.match(prompt,/schema: sh9\.trip-pack\/1/);
 assert.match(prompt,/segments\[\{mode,line,from,to,departure,arrival,status,note\}\]/);
 assert.match(prompt,/alerts\[\{title,text\}\]/);
 assert.match(prompt,/sources\[\{name,url\}\]/);
 assert.match(prompt,/status timetable\/estimated\/unknown/);
 assert.match(prompt,/ismeretlen idő null/);
 assert.match(prompt,/egyetlen tiszta JSON-kódblokkot/);
 const u=new URL(ai.url(q,places,'wait'));
 assert.equal(u.origin,'https://chatgpt.com');
 assert.equal(u.pathname,'/');
 assert.equal(u.searchParams.get('q'),prompt);
 assert.equal([...u.searchParams.keys()].join(','),'q');
});
test('ChatGPT handoff is one user action, no API key, no extra button, never hidden redirects',()=>{
 let count=0,value='';
 const l={assign(u){count++;value=u}};
 assert.equal(ai.go(q,places,'balanced',l),true);
 assert.equal(count,1);
 assert.equal(new URL(value).hostname,'chatgpt.com');
 assert.equal(ai.go({...q,to:''},places,'balanced',l),false);
 assert.equal(ai.go({...q,date:'2026-11-99'},places,'balanced',l),false);
 assert.equal(ai.go({...q,from:'Otthon',to:'Otthon'},places,'balanced',l),false);
 assert.equal(ai.go(q,places,'balanced',{assign(){throw Error('navigation blocked')}}),false);
 assert.equal(count,1);
 const source=read('sh9/smart-travel/public-transport/smart-trip/smart-trip-chatgpt-handoff-v1076.js');
 assert.doesNotMatch(source,/fetch\(|setInterval\(|OPENAI_API_KEY|api\.openai\.com|geolocation|getCurrentPosition/);
 assert.doesNotMatch(source,/window\.open|target=['"]_blank/);
});
test('stale, mismatching or out-of-country favorite coordinates cannot be leaked',()=>{
 const prompt=ai.prompt(q,{origin:{...places.origin,name:'A szomszéd helye'},destination:{...places.destination,lat:40}},'balanced');
 assert.ok(prompt);
 assert.doesNotMatch(prompt,/47\.54512|48\.25343/);
 assert.match(prompt,/Honnan: Otthon/);
 assert.match(prompt,/Hová: Mónika · Anyuka/);
 assert.equal(ai.prompt({...q,time:'99:55'},places,'balanced'),null);
 assert.equal(ai.prompt({...q,from:' '},places,'balanced'),null);
});
