'use strict';
const test=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const base=path.join(__dirname,'..');
const get=p=>fs.readFileSync(path.join(base,p),'utf8');
const dir='android-bridge/app/src/main/java/hu/zsoltmonika/healthhubbridge/';
const admin=get(dir+'OneRemoteAdmin.kt');
const gps=get(dir+'Sh9GpsService.kt');
const worker=get(dir+'OrchestratorWorker.kt');
const app=get(dir+'MainActivity.kt');
const shell=get(dir+'Sh9WebActivity.kt');
const manifest=get('android-bridge/app/src/main/AndroidManifest.xml');
const build=get('android-bridge/app/build.gradle.kts');
const network=get('hh-one-rag-v500.js');
const dispatch=get('live-v305.js');
const guardian=get('guardian/index.html');
const ota=get('guardian/guardian-ota-assistant-v1042.js');
const baseline=JSON.parse(get('data/bridge-ota.json'));
test('candidate newer than signed OTA and original package ID remains stable',()=>{
 assert.match(build,/applicationId = "hu.zsoltmonika.healthhubbridge"/);
 assert.ok(Number(build.match(/versionCode = (\d+)/)[1])>=baseline.versionCode,'installed version cannot be older than signed OTA baseline');
 assert.equal(baseline.channel,'signed-release');
 assert.match(build,/versionName = "0.15.11"/);
 assert.match(manifest,/ACCESS_NETWORK_STATE/);
});
test('remote admin is opt-in, owner-bound, can be revoked, and not a remote shell',()=>{
 assert.match(admin,/KEY_CONSENT = "hh_one_remote_admin_consent_v1041"/);
 assert.match(admin,/getBoolean\(KEY_CONSENT, false\)/);
 assert.match(app,/setPositiveButton\("Egyszer engedélyezem"/);
 assert.match(app,/openSh9WithRemoteAdminConsent\(\)/);
 assert.match(app,/KEY_FIRST_RUN_SHOWN/);
 assert.match(app,/setPositiveButton\("✅ Engedélyezem"/);
 assert.match(app,/setNegativeButton\("Most nem"/);
 assert.match(app,/putBoolean\(OneRemoteAdmin.KEY_CONSENT, allow\)/);
 assert.match(app,/deviceOwnerProfile\(\) == null/);
 assert.match(app,/OneRemoteAdmin\.revoke\(prefs\)/);
 assert.match(app,/putBoolean\(OneRemoteAdmin.KEY_CONSENT, false\)/);
 assert.match(worker,/requestedOwner != owner/);
 assert.match(worker,/commandId == prefs\.getString\(LAST_COMMAND_KEY, null\)/);
 for(const scope of ['gps_repair','remote_config','agent_reconcile'])
   assert.match(worker,new RegExp('"'+scope+'"'));
 assert.match(worker,/OneRemoteAdmin\.consent\(prefs\)/);
 assert.doesNotMatch(admin,/Runtime\.getRuntime|ProcessBuilder|AccessibilityService|setDeviceOwner|EXECUTE|loadUrl|eval\(/i);
 assert.doesNotMatch(admin,/requestPermissions|REQUEST_INSTALL_PACKAGES/);
});
test('remote GPS repair is bounded, existing/consented and NEVER fake a fresh GPS fix',()=>{
 assert.match(gps,/240_000L/);
 assert.match(gps,/15 \* 60_000L/);
 assert.match(gps,/repairCount < 2/);
 assert.match(gps,/FamilyGuardContinuity\.canRestart/);
 assert.match(gps,/removeCallbacks\(watchdog\)/);
 assert.match(gps,/fun recoverActive\(\): String/);
 assert.match(admin,/Sh9GpsService\.recoverActive\(\)/);
 assert.match(admin,/FamilyGuardContinuity\.restartApprovedGps\(context\)/);
 assert.match(worker,/steps\.put\(step\(scope, "SH9 Remote Admin", "queued", outcome\)\)/);
 assert.match(admin,/gpsIntervalSeconds/);
 assert.match(admin,/15, 30, 60/);
 assert.match(dispatch,/gps_repair','remote_config','agent_reconcile/);
 assert.match(dispatch,/adminConfig\.gpsIntervalSeconds/);
 assert.match(network,/GPS SERVICE REPAIR/);
});
