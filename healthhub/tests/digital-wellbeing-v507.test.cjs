'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const vm=require('node:vm');
const base=path.join(__dirname,'..');
const src=fs.readFileSync(path.join(base,'digital-health/digital-usage-vault-v507.js'),'utf8');
const mod={exports:{}};
vm.runInNewContext(src,{module:mod,Date,Intl,Set,Map,Number,Math,Error,URLSearchParams});
const api=mod.exports;
assert.equal(api.SCHEMA,'healthhub.digital-wellbeing/1');
const HOUR=3600000;
const now=Date.parse('2026-10-14T12:00:00Z');
const hour=now-2*HOUR;
const good={schema:api.SCHEMA,source:api.SOURCE,profileKey:'zsolt',retentionDays:30,
 missingIsUnknown:true,shared:true,collectedAtMs:now,
 hours:[{hourStartMs:hour,observedForegroundMs:900000,chatGptForegroundMs:180000,sessionFragments:2}]};
const clone=x=>JSON.parse(JSON.stringify(x));
assert.equal(api.validate(good,'zsolt',now).hours.length,1);
assert.equal(api.summary(api.validate(good,'zsolt',now),1,now).observed,900000);
assert.equal(api.summary(api.validate(good,'zsolt',now),1,now).chatgpt,180000);
assert.equal(api.summary(api.validate(good,'zsolt',now),30,now).covered,1);
assert.equal(api.summary(api.validate(good,'zsolt',now),1,now).dayHours.filter(x=>x!==null).length,1);
assert.throws(()=>api.validate(good,'monika',now),/forrás|profil/i);
const revoked=clone(good);revoked.shared=false;
assert.throws(()=>api.validate(revoked,'zsolt',now),/forrás|profil/i);
const duplicate=clone(good);duplicate.hours.push({...duplicate.hours[0]});
assert.throws(()=>api.validate(duplicate,'zsolt',now),/duplikált/i);
const fake=clone(good);fake.hours[0].observedForegroundMs=HOUR+1;
assert.throws(()=>api.validate(fake,'zsolt',now),/idősáv/i);
const over=clone(good);over.hours[0].chatGptForegroundMs=2000000;
assert.throws(()=>api.validate(over,'zsolt',now),/idősáv/i);
const stale=clone(good);stale.collectedAtMs=now-32*86400000;
assert.throws(()=>api.validate(stale,'zsolt',now),/idő/i);
const missing={...good,hours:[]};
const s=api.summary(api.validate(missing,'zsolt',now),7,now);
assert.equal(s.covered,0);
assert.equal(s.dayTotals.filter(x=>x.foregroundMs===null).length,7,'Missing days are unknown, never false zero');
const fallA=Date.parse('2026-10-25T00:00:00Z');
const fallB=Date.parse('2026-10-25T01:00:00Z');
assert.equal(api.local(fallA).date,api.local(fallB).date);
assert.equal(api.local(fallA).hour,api.local(fallB).hour,'DST repeated hour groups in Budapest-local day');
const html=fs.readFileSync(path.join(base,'digital-health/index.html'),'utf8');
assert.match(html,/digital-usage-vault-v507\.js\?v=507-private-source/);
assert.match(html,/digital-live-v507\.js\?v=507-real-stats/);
assert.match(html,/HH_DW_LIVE_V507\.refresh\(profile,period\)/);
const native=fs.readFileSync(path.join(base,'android-bridge/app/src/main/java/hu/zsoltmonika/healthhubbridge/dw/DigitalUsageCloudSync.kt'),'utf8');
assert.match(native,/DropboxVaultClient\.PROFILES_DIR/);
assert.match(native,/owner \+ "-digital-wellbeing\.json"/);
assert.match(native,/CLOUD_ENABLED/);
assert.match(native,/"retentionDays", 30/);
assert.doesNotMatch(native,/AppDetailLedger\.read/,'never upload per-app names without distinct opt-in');
console.log('HH One Digital Wellbeing private source, 30-day retention, profile isolation, DST, missing=unknown PASS');
