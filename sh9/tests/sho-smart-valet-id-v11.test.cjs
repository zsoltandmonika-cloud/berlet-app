test('identity photos are encrypted in-browser with nonexportable AES-GCM key, random 16-byte salt & 12-byte IV',async()=>{
 assert.match(app,/ITERATIONS=310000/);
 assert.match(app,/PBKDF2/);
 assert.match(app,/AES-GCM/);
 assert.match(app,/getRandomValues\(new Uint8Array\(12\)\)/);
 assert.match(app,/getRandomValues\(new Uint8Array\(16\)\)/);
 assert.match(app,/const aad=.*additionalData|additionalData:aad\(rec,which\)/);
 assert.match(app,/new Blob\(\[iv,new Uint8Array\(ciphertext\)\]/);
 assert.match(app,/contentType:'application\/octet-stream',upsert:false/);
 assert.match(app,/if\(password\.length<12\)/);
 assert.match(page,/id="svIdPassConfirmV11"/);
 assert.match(app,/password!==\$\('svIdPassConfirmV11'\)\.value/);
 assert.match(app,/activeKey=null/);
 assert.doesNotMatch(app,/localStorage\.setItem|sessionStorage\.setItem|getPublicUrl|createSignedUrl|service_role|toDataURL|FaceDetector|BarcodeDetector|Tesseract/i);
 const inject=app.replace(/\}\)\(window,document\);\s*$/,
  'window.__probe={derive,encrypt,decrypt,salt,b64,aad};})(window,document);');
 assert.notEqual(inject,app);
 const window={crypto:webcrypto,localStorage:{getItem(){return 'z'}},HH_CENTRAL_VAULT:{}};
 const document={readyState:'loading',addEventListener(){}};
 const context={window,document,Blob,Uint8Array,TextEncoder,TextDecoder,atob,btoa,URL,Array};
 vm.runInNewContext(inject,context,{filename:'identity-v11-probe.js'});
 const probe=window.__probe;
 const saltBytes=webcrypto.getRandomValues(new Uint8Array(16));
 const pass='A strong sample phrase 2026!';
 const key=await probe.derive(pass,saltBytes);
 assert.equal(key.extractable,false);
 assert.equal(key.algorithm.name,'AES-GCM');
 const item={profile_key:'zsolt',doc_type:'license',id:'11111111-1111-4111-8111-111111111111'};
 const original=new Blob([Uint8Array.from([255,216,255,88,21,45,60])],{type:'image/jpeg'});
 const cipher=await probe.encrypt(original,key,item,'front');
 const cipherArray=new Uint8Array(await cipher.arrayBuffer());
 assert.equal(cipher.type,'application/octet-stream');
 assert.equal(cipherArray.length,original.size+12+16);
 assert.notDeepEqual(cipherArray.slice(12),new Uint8Array(await original.arrayBuffer()));
 const plaintext=await probe.decrypt(cipher,key,item,'front');
 assert.deepEqual(new Uint8Array(await plaintext.arrayBuffer()),new Uint8Array(await original.arrayBuffer()));
 await assert.rejects(probe.decrypt(cipher,key,item,'back'),/BAD_PASS/);
 await assert.rejects(probe.decrypt(cipher,key,{...item,profile_key:'monika'},'front'),/BAD_PASS/);
 const wrong=await probe.derive('Completely different phrase!',saltBytes);
 await assert.rejects(probe.decrypt(cipher,wrong,item,'front'),/BAD_PASS/);
 assert.equal(probe.b64(saltBytes).length,24);
});
